# Actual serial mathematical oracles, without TMB/glmmTMB loading or compilation.
args <- commandArgs(trailingOnly = TRUE)
if (length(args) != 1L) stop("Usage: Rscript tests/pure.R REFERENCE_SOURCE")
root <- normalizePath(args[1], mustWork = TRUE)
source(file.path(root, "R/common.R"))
source(file.path(root, "R/regularization.R"))
source(file.path(root, "R/native_cases.R"))
X <- cbind(1, rep(c(-1, 1), 10), rep(c(-1, -1, 1, 1), 5))
y <- as.numeric(X %*% c(2, 0.8, 0.03))
fit <- reference_lasso(X, y, 1, c(0, 2, 2))
reference_close(fit$beta, c(2, 0.7, 0), 1e-12)
reference_assert(fit$kkt_inf < 1e-10, "Exact lasso KKT failed")
posterior <- reference_gaussian_posterior(matrix(1, 3, 1), c(1, 2, 3), 1, 0, 1, matrix(1, 1, 1))
reference_close(posterior$mean, 1.5, 1e-12)
reference_close(posterior$covariance, 0.25, 1e-12)
reference_close(posterior$prediction$sd, sqrt(1.25), 1e-12)
conditional <- reference_conditional(2, 0, 0, matrix(1, 1, 1), matrix(0.5, 1, 1), matrix(1, 1, 1))
reference_close(conditional$mean, 1, 1e-12)
reference_close(conditional$covariance, 0.75, 1e-12)
reference_close(reference_gaussian_nll(c(0, 0), diag(2)), log(2 * pi), 1e-12)
invalid <- try(reference_lasso(X, y, 1, c(1, -1, 1)), silent = TRUE)
reference_assert(inherits(invalid, "try-error"), "Negative lasso penalty must fail")
parameters <- list(log_tau = log(c(0.5, 0.2)), phi_coordinate = atanh(-0.4), log_sigma = log(0.3), scale_trend = 0)
covariance <- reference_panel_covariance(0:2, 0:2, parameters, 1)
reference_assert(min(eigen(covariance, symmetric = TRUE)$values) > 0, "Panel covariance is not positive definite")
reference_close(covariance[1, 2], 0.25 - 0.09 * 0.4, 1e-12)
cat("Passed six serial mathematical/input oracle groups; no TMB or glmmTMB runtime claim\n")

quadrature <- reference_quadrature(function(value) -dnorm(value, 0.5, 2, log = TRUE), 0.5, 2, 2)
reference_close(quadrature$negative_log_integral, 0, 1e-8)
reference_assert(quadrature$relative_interval_change < 1e-7, "Gaussian quadrature interval check failed")
invalid_quadrature <- try(reference_quadrature(function(value) NaN, 0, 1, 1), silent = TRUE)
reference_assert(inherits(invalid_quadrature, "try-error"), "Nonfinite quadrature must fail")

state <- new.env(parent = emptyenv())
state$last.par <- c(50, 99)
state$last.par.best <- c(-100, 100)
state$lfixed <- function() c(TRUE, FALSE)
state$parList <- function(x, par) list(beta = x, latent = par[2])
objective <- list(
  env = state,
  fn = function(x) {
    state$last.par <- c(x, 2 * x)
    x^2
  },
  report = function(par) list(effect = par[2])
)
restored <- reference_restore_fit(objective, 2, 4)
reference_close(restored$parameters$beta, 2, 1e-12)
reference_close(restored$parameters$latent, 4, 1e-12)
reference_close(restored$report$effect, 4, 1e-12)
reference_close(state$last.par.best, c(-100, 100), 1e-12)

counts <- matrix(c(1, 3, 2, 1), nrow = 2)
summary <- reference_simulation_summary(list(counts, counts), "betabinomial", 2L, c(3, 4))
reference_close(summary[[1]]$mean_success_count, 2, 1e-12)
reference_close(summary[[1]]$mean_success_proportion, (1 / 3 + 3 / 4) / 2, 1e-12)
invalid_counts <- try(reference_simulation_summary(list(counts, counts), "betabinomial", 2L, c(4, 4)), silent = TRUE)
reference_assert(inherits(invalid_counts, "try-error"), "Changed trial totals must fail")
flattened_counts <- try(reference_simulation_summary(list(as.numeric(counts), as.numeric(counts)), "betabinomial", 2L, c(3, 4)), silent = TRUE)
reference_assert(inherits(flattened_counts, "try-error"), "Flattened binomial simulations must fail")
cat("Passed three additional quadrature, mutable-state and simulation-shape groups; no upstream fitting claim\n")
