# r-043: complete reference for the declared synthetic inputs.
d <- data.frame(x = 0:4, y = c(1, 3, 4, 7, 8))
fit <- lm(y ~ x, data = d)
X <- model.matrix(fit)
stopifnot(identical(dim(X), c(5L, 2L)), all(X[, 1] == 1))
stopifnot(max(abs(as.numeric(X %*% coef(fit)) - fitted(fit))) < 1e-10)
stopifnot(isTRUE(all.equal(as.numeric(predict(fit, data.frame(x = 5))), 10, tolerance = 1e-10)))
g <- data.frame(x = rep(0:2, 2), group = factor(rep(c("A", "B"), each = 3), levels = c("A", "B")))
g$y <- ifelse(g$group == "A", 1 + 2 * g$x, 4 + g$x)
interaction <- lm(y ~ x * group, data = g)
stopifnot(max(abs(unname(coef(interaction)) - c(1, 2, 3, -1))) < 1e-10)
d$double_x <- 2 * d$x
aliased <- lm(y ~ x + double_x, data = d)
stopifnot(qr(model.matrix(aliased))$rank < ncol(model.matrix(aliased)), anyNA(coef(aliased)))
stopifnot(max(abs(crossprod(X, residuals(fit)))) < 1e-10)
ci <- predict(fit, data.frame(x = 2), interval = "confidence")
pi <- predict(fit, data.frame(x = 2), interval = "prediction")
stopifnot(diff(pi[1, c("lwr", "upr")]) > diff(ci[1, c("lwr", "upr")]))
cat("r-043 reference checks passed\n")
