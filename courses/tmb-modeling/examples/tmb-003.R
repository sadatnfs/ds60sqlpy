y <- c(1, 2, 4, 7)
mu <- mean(y)
sigma <- sqrt(mean((y - mu)^2))
nll <- function(y, mu, sigma) length(y) * log(sigma * sqrt(2 * pi)) + sum((y - mu)^2) / (2 * sigma^2)
print(c(mean = mu, ml_sd = sigma, sample_sd = sd(y)))
stopifnot(abs(nll(y, mu, sigma) + sum(dnorm(y, mu, sigma, log = TRUE))) < 1e-12)
y3 <- rep(y, 3)
stopifnot(mean(y3) == mu, abs(nll(y3, mu, sigma) - 3 * nll(y, mu, sigma)) < 1e-10)
print(c(original_nll = nll(y, mu, sigma), duplicated_nll = nll(y3, mu, sigma)))
