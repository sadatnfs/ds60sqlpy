path <- tempfile(fileext = ".csv")
original <- data.frame(id = c("001", "002"), amount = c(2, NA_real_))
write.csv(original, path, row.names = FALSE, na = "")
restored <- read.csv(path, colClasses = c("character", "numeric"), na.strings = "")
stopifnot(identical(restored, original), identical(names(restored), c("id", "amount")))
unlink(path)
path <- tempfile(fileext = ".rds")
x <- structure(c(1, 2), names = c("A", "B")); saveRDS(x, path)
stopifnot(identical(readRDS(path), x)); unlink(path)
encoded <- jsonlite::toJSON(list(values = I(c(2))), auto_unbox = TRUE)
restored <- jsonlite::fromJSON(encoded, simplifyVector = FALSE)
stopifnot(is.list(restored$values), restored$values[[1]] == 2)
