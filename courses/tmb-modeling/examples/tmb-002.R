x <- c(-1, 0, 1, 2)
X <- cbind(intercept = 1, x = x)
beta <- c(intercept = 2, x = .5)
print(drop(X %*% beta))
stopifnot(nrow(X) == length(x), ncol(X) == length(beta))
wrong <- matrix(x, ncol = 1)
shape_ok <- function(design, parameter) ncol(design) == length(parameter)
print(list(valid = shape_ok(X, beta), rejected = !shape_ok(wrong, beta)))
stopifnot(!shape_ok(wrong, beta))
