y <- c(1, 2, 4, 7)
objective <- function(s) -sum(dnorm(y, mean(y), exp(s), log = TRUE))
fit <- optimize(objective, interval = c(-3, 3))
print(c(log_sd = fit$minimum, sd = exp(fit$minimum)))
